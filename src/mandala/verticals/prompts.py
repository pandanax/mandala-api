def get_vertical_system_prompt(vertical_id: str) -> str:
    """Вернуть системный промпт для slug вертикали или дефолт."""
    key = vertical_id.strip()
    return VERTICAL_SYSTEM_PROMPTS.get(key, _DEFAULT_SYSTEM)
